#!/usr/bin/env bash
# Build dist/jinja.sh: jinja.sh with the awk engine embedded (single file).
set -eu
root=$(cd "${BASH_SOURCE[0]%/*}/.." && pwd)
out=${1:-$root/dist/jinja.sh}
mkdir -p "${out%/*}"
# shellcheck disable=SC1091
source "$root/jinja.sh"
{
	# everything up to the library location block
	sed -n '1,/^if \[\[ -z \${_JINJA_LIB:-} \]\]; then$/p' "$root/jinja.sh" | sed '$d'
	printf '%s\n' "# awk engine (generated by tools/build.sh from lib/awk/*.awk)"
	printf '%s\n' "IFS= read -r -d '' _JINJA_AWK_SRC <<'_JINJA_AWK_EOF' || true"
	for f in "${_JINJA_AWK_FILES[@]}"; do
		# drop comment-only lines and leading indentation to keep it small
		sed -e '/^[[:space:]]*#/d' -e '/^[[:space:]]*$/d' -e 's/^[[:space:]]*//' "$root/lib/awk/$f.awk"
	done
	printf '%s\n' "_JINJA_AWK_EOF"
	# the rest after the library location block
	sed -n '/^_JINJA_AWK_FILES=/,$p' "$root/jinja.sh"
} >"$out"
chmod +x "$out"
printf 'built %s (%d bytes)\n' "$out" "$(wc -c <"$out")"
